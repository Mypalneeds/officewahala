function symbol(name, file) {
  const svg = fs.readFileSync(path.join(FA, file + '.svg'), 'utf8');
  const vb = svg.match(/viewBox="([^"]+)"/)[1];
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => `<path d="${m[1]}"/>`).join('');
  return `<symbol id="i-${name}" viewBox="${vb}">${paths}</symbol>`;
}

